    netsurf_src += [
        "netsurf/content/handlers/javascript/fetcher.c",
        "netsurf/content/handlers/javascript/none/none.c",
    ]
    netsurf_src += _rels(self, "netsurf/content/handlers/html/*.c")
    netsurf_src += ["netsurf/content/handlers/text/textplain.c"]
    netsurf_src += _rels(self, "netsurf/utils/*.c")
    netsurf_src += _rels(self, "netsurf/utils/http/*.c")
    netsurf_src += _rels(self, "netsurf/utils/nsurl/*.c")

