    libdom_src = [*_rels(self, "libdom/src/**/*.c"), "libdom/bindings/hubbub/parser.c", "libdom/bindings/xml/expat_xmlparser.c"]
    libhubbub_src = _rels(self, "libhubbub/src/**/*.c")
    libparserutils_src = _rels(self, "libparserutils/src/**/*.c")
    libnsbmp_src = _rels(self, "libnsbmp/src/*.c")
    libnsgif_src = _rels(self, "libnsgif/src/*.c")
    libnsutils_src = _rels(self, "libnsutils/src/*.c")
    libsvgtiny_src = _rels(self, "libsvgtiny/src/*.c", ("autogenerated_colors.c",))
    libwapcaplet_src = _rels(self, "libwapcaplet/src/*.c")

    netsurf_src = []
    netsurf_src += _rels(self, "netsurf/desktop/*.c")
    netsurf_src += _rels(self, "netsurf/frontends/tiny/*.c")
    netsurf_src += _rels(self, "netsurf/content/*.c", ("fs_backing_store.c",))
    netsurf_src += _rels(self, "netsurf/content/fetchers/*.c")
