url = "https://www.denx.de/wiki/U-Boot"
source = "https://github.com/u-boot/u-boot/archive/refs/tags/v2021.04.tar.gz"
sha256 = "c51a62092c7c18c249febe31457f3c811d2d3296a9186d241ad23a2fb0a794f2"
# host image tools only, as in the Oasis recipe
options = ["!check"]

_cflags = [
    "-DUSE_HOSTCC",
    "-I.", "-Itools",
    "-idirafter", "include",
    "-include", "include/compiler.h",
]

_sources = [
    "tools/aisimage.c", "tools/atmelimage.c", "tools/default_image.c",
    "tools/imagetool.c", "tools/imx8image.c", "tools/imx8mimage.c",
    "tools/kwbimage.c", "tools/lpc32xximage.c", "tools/mxsimage.c",
    "tools/omapimage.c", "tools/os_support.c", "tools/pblimage.c",
    "tools/pbl_crc32.c", "tools/vybridimage.c", "tools/stm32image.c",
    "tools/rkcommon.c", "tools/rkimage.c", "tools/rksd.c", "tools/rkspi.c",
    "tools/socfpgaimage.c", "tools/ublimage.c", "tools/zynqimage.c",
    "tools/zynqmpimage.c", "tools/zynqmpbif.c", "tools/gpimage.c",
    "tools/gpimage-common.c", "tools/mtk_image.c",
    "common/bootm.c", "common/image.c", "common/hash.c",
    "lib/crc16.c", "lib/crc32.c", "lib/fdtdec.c", "lib/md5.c", "lib/rc4.c",
    "lib/sha1.c", "lib/sha256.c",
]


def pre_build(self):
    self.mkdir("include/generated", parents=True)
    for hdr in ("timestamp_autogenerated.h", "version_autogenerated.h"):
        self.cp(self.template_path / "generated" / hdr, self.cwd / "include/generated" / hdr)


def build(self):
    from cbuild.util import compiler

    cc = compiler.C(self)
    self.mkdir("obj", parents=True)
    objs = []
    for src in _sources:
        obj = "obj/" + src.replace("/", "_") + ".o"
        cc.invoke([src], obj, obj_file=True, flags=_cflags)
        objs.append(obj)
    cc.invoke(
        ["lib/sha512.c"], "obj/sha512.o", obj_file=True,
        flags=_cflags + ["-DCONFIG_SHA384", "-DCONFIG_SHA512"],
    )
    objs.append("obj/sha512.o")
    cc.invoke(["tools/mkimage.c", *objs], "mkimage", flags=_cflags)
    cc.invoke(["tools/dumpimage.c", *objs], "dumpimage", flags=_cflags)


def install(self):
    self.install_bin("mkimage")
    self.install_bin("dumpimage")
    self.install_license("Licenses/README")
